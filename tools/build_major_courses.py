# 写法：("课名", "b|c|e", "技能1,技能2:0.5") —— b=专业基础课 c=专业核心课 e=专业拓展课，
# 技能默认 1.0（独立教学单元），":0.5" 表示涉及/支撑。技能名必须先在 skill_dict.csv 里。
_TYPE = {"b": "专业基础课", "c": "专业核心课", "e": "专业拓展课"}


def _mk(code: str, name: str, category: str, jobs: str, rows: list) -> dict:
    out = []
    for cname, t, spec in rows:
        ss = []
        for part in spec.split(","):
            part = part.strip()
            if not part:
                continue
            if ":" in part:
                s, w = part.split(":")
                ss.append((s.strip(), float(w)))
            else:
                ss.append((part, 1.0))
        out.append((cname, _TYPE[t], ss))
    return dict(code=code, name=name, category=category, jobs=jobs, courses=out)


