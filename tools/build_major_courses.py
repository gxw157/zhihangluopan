def main() -> None:
    known = set(pd.read_csv(DICT / "skill_dict.csv", encoding="utf-8-sig")["canonical"].astype(str))
    bad = sorted({s for m in MAJORS for _, _, ss in m["courses"] for s, _ in ss if s not in known})
    if bad:
        raise SystemExit("以下技能不在 skill_dict.csv 中，请先补词典或改名：" + "、".join(bad))

    major_rows, course_rows, map_rows = [], [], []
    for m in MAJORS:
        n_base = sum(1 for _, t, _ in m["courses"] if t == "专业基础课")
        n_core = sum(1 for _, t, _ in m["courses"] if t == "专业核心课")
        n_ext = sum(1 for _, t, _ in m["courses"] if t == "专业拓展课")
        major_rows.append({
            "code": m["code"], "name": m["name"], "category": m["category"],
            "level": "高职专科", "years": 3, "jobs": m["jobs"],
            "courses": len(m["courses"]), "base": n_base, "core": n_core, "ext": n_ext,
            "families": FAMILIES.get(m["code"], []),
        })
        for i, (cname, ctype, skills) in enumerate(m["courses"], 1):
            cid = f"{m['code']}-C{i:02d}"
            course_rows.append({
                "major_code": m["code"], "major_name": m["name"], "course_id": cid,
                "course_name": cname, "credits": "", "hours": "", "term": "", "type": ctype,
                "standard": f"{SOURCE}·{ctype}",
            })
            for s, score in skills:
                map_rows.append({
                    "major_code": m["code"], "major_name": m["name"],
                    "course_id": cid, "course_name": cname, "skill": s,
                    "score": score,
                    "evidence_type": "unit" if score >= 1.0 else "mention",
                    "evidence_ref": f"{SOURCE}·{m['name']}·{ctype}",
                    "standard": f"{SOURCE}·{ctype}",
                })

    majors = {
        "version": "2026-11-04",
        "source": SOURCE,
        "note": "专业基础课 / 专业核心课的课程名称与课程组依据教育部《职业教育专业教学标准（2025年修订）》；"
                "专业拓展课为各校实施性方案中的常见课程，标准只给方向、不强制列名；"
                "学分学时未从标准摘录，各校按本校人才培养方案填写。",
        "default": "510209",
        "majors": major_rows,
    }
    (DICT / "majors.json").write_text(json.dumps(majors, ensure_ascii=False, indent=2), encoding="utf-8")

    def dump(path: Path, rows: list[dict], fields: list[str]) -> None:
        # 先写临时文件再原子替换：文件被 Excel/WPS 打开时也能安全落盘，且不会写坏原文件
        tmp = path.with_name(path.stem + "_tmp" + path.suffix)
        with open(tmp, "w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=fields)
            w.writeheader()
            w.writerows(rows)
        os.replace(tmp, path)

    dump(DICT / "courses.csv", course_rows,
         ["major_code", "major_name", "course_id", "course_name", "credits", "hours", "term", "type", "standard"])
    dump(DICT / "course_skill_map.csv", map_rows,
         ["major_code", "major_name", "course_id", "course_name", "skill", "score",
          "evidence_type", "evidence_ref", "standard"])

    print(f"专业 {len(MAJORS)} 个 | 课程 {len(course_rows)} 门 | 映射 {len(map_rows)} 条")


if __name__ == "__main__":
    main()
